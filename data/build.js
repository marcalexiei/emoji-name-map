const fs = require('fs');
const dataSource = require('emoji-datasource');
const jsonData = {};

dataSource.forEach((source) => {
    const { unified, short_name } = source;
    hexArray = unified.split('-').map((hexStr) => parseInt(`0x${hexStr}`, 16));
    const codeUnit = String.fromCodePoint(...hexArray);
    jsonData[short_name] = codeUnit;
});

function writeFile(path, data) {
    const jsonStr = JSON.stringify(data);
    fs.writeFile(path, jsonStr, (err) => {
        if (err) console.error(err);
        if (!err) {
            console.log('Success output to json!!');
        }
    });
}

/**
 * Writes the `EmojiName` union, so the declarations cannot drift from the data.
 *
 * @name writeTypes
 * @function
 * @param {string} path The output path of the declaration file.
 * @param {Record<string, string>} data The name to unicode emoji mapping.
 */
function writeTypes(path, data) {
    const header = '// Generated by `npm run data:build`. Do not edit.';
    const names = Object.keys(data)
        .map((name) => JSON.stringify(name))
        .join(' | ');
    fs.writeFileSync(path, `${header}\nexport type EmojiName = ${names};\n`);
}

writeFile(`lib/datasource.json`, jsonData);
writeTypes(`lib/emoji-name.d.ts`, jsonData);
